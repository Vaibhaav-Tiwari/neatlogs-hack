// Writes site/logo-frames.js from the real CLI animation in cli/logo.ts, so the
// terminal on the page replays exactly what `tally logo` draws.
// Run `npm run build` first, then `node site/tools/build-frames.mjs`.
import { writeFileSync } from 'node:fs';
import { FRAME_MS, compactLogo, logoFrames } from '../../dist/cli/logo.js';

const escapeHtml = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** One line of truecolour terminal output as HTML. Only the styles the logo uses are known; anything else fails loudly. */
export function ansiToHtml(line) {
  let html = '';
  let open = false;
  for (const part of line.split(/(\x1b\[[0-9;]*m)/)) {
    const match = /^\x1b\[([0-9;]*)m$/.exec(part);
    if (!match) { html += escapeHtml(part); continue; }
    if (open) { html += '</span>'; open = false; }
    if (match[1] === '0' || match[1] === '') continue;
    const classes = [];
    const codes = match[1].split(';');
    for (let i = 0; i < codes.length; i++) {
      if (codes[i] === '1') classes.push('b');
      else if (codes[i] === '2') classes.push('d');
      else if (codes[i] === '3') classes.push('i');
      else if ((codes[i] === '38' || codes[i] === '48') && codes[i + 1] === '2') { classes.push(codes[i] === '38' ? 's' : 'sb'); i += 4; }
      else throw new Error(`Unexpected terminal style ${match[1]} in a logo frame`);
    }
    html += `<span class="${classes.join(' ')}">`;
    open = true;
  }
  return html + (open ? '</span>' : '');
}

export function frameData() {
  const page = (lines) => lines.map((line) => ansiToHtml(` ${line}`)).join('\n');
  return { frameMs: FRAME_MS, frames: logoFrames('truecolor').map(page), compact: page(compactLogo('truecolor')) };
}

export function frameScript() {
  return `// Generated by site/tools/build-frames.mjs from cli/logo.ts. Do not edit by hand.\nwindow.TALLY_LOGO = ${JSON.stringify(frameData())};\n`;
}

if (import.meta.url === `file://${process.argv[1]}`) {
  writeFileSync(new URL('../logo-frames.js', import.meta.url), frameScript());
  console.log(`wrote site/logo-frames.js: ${frameData().frames.length} frames`);
}
