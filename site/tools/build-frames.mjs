// Regenerates everything on the page that comes from the real CLI animation in
// cli/logo.ts: the terminal's frames, the pixel mark in the hero and nav, and the favicon.
// Run `npm run build` first, then `node site/tools/build-frames.mjs`.
import { readFileSync, writeFileSync } from 'node:fs';
import { FRAME_MS, compactLogo, logoFrames } from '../../dist/cli/logo.js';
import { markSvg } from './mark-svg.mjs';

const escapeHtml = (text) => text.replace(/&/g, '&amp;').replace(/</g, '&lt;').replace(/>/g, '&gt;');

/** One line of truecolour terminal output as HTML. Only the styles the logo uses are known; anything else fails loudly. */
export function ansiToHtml(line) {
  let html = '';
  let open = false;
  for (const part of line.split(/(\x1b\[[0-9;]*m)/)) {
    const match = /^\x1b\[([0-9;]*)m$/.exec(part);
    if (!match) { html += escapeHtml(part); continue; }
    if (open) { html += '</span>'; open = false; }
    if (match[1] === '0' || match[1] === '') continue;
    const classes = [];
    const codes = match[1].split(';');
    for (let i = 0; i < codes.length; i++) {
      if (codes[i] === '1') classes.push('b');
      else if (codes[i] === '2') classes.push('d');
      else if (codes[i] === '3') classes.push('i');
      else if ((codes[i] === '38' || codes[i] === '48') && codes[i + 1] === '2') { classes.push(codes[i] === '38' ? 's' : 'sb'); i += 4; }
      else throw new Error(`Unexpected terminal style ${match[1]} in a logo frame`);
    }
    html += `<span class="${classes.join(' ')}">`;
    open = true;
  }
  return html + (open ? '</span>' : '');
}

const frames = logoFrames('truecolor');
const page = (lines) => lines.map((line) => ansiToHtml(` ${line}`)).join('\n');
const data = { frameMs: FRAME_MS, frames: frames.map(page), compact: page(compactLogo('truecolor')) };
writeFileSync(new URL('../logo-frames.js', import.meta.url), `// Generated by site/tools/build-frames.mjs from cli/logo.ts. Do not edit by hand.\nwindow.TALLY_LOGO = ${JSON.stringify(data)};\n`);

// Splice generated markup between marker comments in index.html.
const indexUrl = new URL('../index.html', import.meta.url);
let html = readFileSync(indexUrl, 'utf8');
const splice = (name, markup) => {
  const start = `<!-- ${name}:start -->`, end = `<!-- ${name}:end -->`;
  const a = html.indexOf(start), b = html.indexOf(end);
  if (a < 0 || b < 0) throw new Error(`index.html has no ${name} markers`);
  html = html.slice(0, a + start.length) + markup + html.slice(b);
};
splice('hero-mark', markSvg(frames));
splice('nav-mark', markSvg(frames, { crop: 19, animate: false, title: 'Tally', className: 'pixel-mark small' }));
splice('term-frame', data.frames.at(-1));
writeFileSync(indexUrl, html);

const icon = markSvg(frames, { crop: 19, animate: false, title: 'Tally' }).replace(/^<svg[^>]*>/, '').replace('</svg>', '');
writeFileSync(new URL('../favicon.svg', import.meta.url), `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 64"><rect width="64" height="64" rx="12" fill="#1b1e27"/><g transform="translate(8 6) scale(2.5 2.6)" shape-rendering="crispEdges"><style>.ink{fill:#f2f2f0}.sl{fill:#f0703a}</style>${icon}</g></svg>\n`);
console.log(`wrote logo-frames.js (${frames.length} frames), the hero and nav marks, the terminal frame and favicon.svg`);
